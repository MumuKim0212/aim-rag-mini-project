def ext(f, p, start, end):
    t = pg[(f, p)]
    idx = [k for k, c in enumerate(t) if not c.isspace()]
    flat = ''.join(t[k] for k in idx)
    ws = lambda x: ''.join(c for c in x if not c.isspace())
    a = flat.index(ws(start))
    b = flat.index(ws(end), a) + len(ws(end)) - 1
    return (f, p, t[idx[a]:idx[b] + 1])


def rec(n, q, beh, ans, inc, exc, ev, diff, cat, ctx, qtype, kind, note='', targets=None):
    ev_pages = [{'file': f, 'page': p, 'source': 'vlm' if VLM in pg[(f, p)] and pg[(f, p)].index(x) > pg[(f, p)].index(VLM) else 'text'} for f, p, x in ev]
    srcs = {e['source'] for e in ev_pages}
    tg = targets or sorted({(f, p) for f, p, _ in ev})
    return {'qid': f'SELFB{n:03d}', 'split': 'test', 'set': 'self2', 'question': q, 'answerable': bool(ev), 'expected_behavior': beh,
            'target_answer': ans, 'must_include': inc, 'must_not_include': exc, 'evidence': [x for _, _, x in ev], 'evidence_pages': ev_pages,
            'evidence_source': '+'.join(s for s in ('text', 'vlm') if s in srcs) if ev else None,
            'targets': [{'file': f, 'page': p} for f, p in tg] if ev else [], 'source_kind': kind, 'difficulty': diff, 'category': cat,
            'context_type': ctx, 'question_type': qtype, 'note': note}


